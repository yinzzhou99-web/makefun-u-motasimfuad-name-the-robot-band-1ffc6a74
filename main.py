"""make.fun entry: Name the Robot Band.

Stdlib-only, deterministic: writes one line to /output/entry.txt
(or $OUTPUT_DIR/entry.txt). Never deletes anything.
"""

import os
from pathlib import Path

LINE = "Rust in Peace, the all-robot metal band whose hit single 'Error 404: Feelings Not Found' is just four toasters screaming in harmony."

def main() -> None:
    out_dir = Path(os.environ.get("OUTPUT_DIR", "/output"))
    out_dir.mkdir(parents=True, exist_ok=True)
    # Gate: 1-200 chars of non-whitespace UTF-8 text, one line only.
    # Judge weighs band name + hit song, first-read laugh, second laugh from
    # the song line fitting the name, and a name worth repeating to a friend.
    assert LINE == LINE.strip() and 1 <= len(LINE) <= 200
    assert "\n" not in LINE
    target = out_dir / "entry.txt"
    target.write_text(LINE, encoding="utf-8")
    target.chmod(0o644)

if __name__ == "__main__":
    main()
